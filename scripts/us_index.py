#!/usr/bin/env python3
"""Zero-token bookkeeping for books. Run after any change to a book.

    python3 scripts/us_index.py [BOOK]        no BOOK: every book under the book root

Per chapter: the contents list under '# Chapter N: Title', between <!-- contents --> and <!-- /contents -->.
Per book: README.md, KEYTERMS.md, INDEX.md, and FACTS.md when the book has a checked mark or an unrun
block. At the book root: manifest.json and search.json for the reading page.
A file is written only when its text changes; nothing is read from the private folder.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import us_bookfmt as bf  # noqa: E402
import us_plan  # noqa: E402

NOTE = "<!-- generated by scripts/us_index.py; do not edit -->"
SCHEMA = 3


def write_if_changed(path, text):
    """Write text unless the file already holds it; True if written."""
    if os.path.exists(path) and bf.read_text(path) == text:
        return False
    bf.write_text(path, text)
    return True

# ---------------------------------------------------------------- contents block


def contents_lines(doc):
    """The list items of a chapter's contents block."""
    return ["- [%s %s](#%s)" % (s.number, s.title, bf.anchor("%s %s" % (s.number, s.title))) for s in doc.sections]


def with_contents(text):
    """Chapter text with its contents block created or refreshed; nothing else changes."""
    doc = bf.parse_chapter(text)
    if not doc.title_line:
        return text
    lines = text.split("\n")
    items = contents_lines(doc)
    span = bf.contents_span(lines)
    if span:
        start, end = span
        return "\n".join(lines[:start + 1] + items + lines[end:])
    block = ["<!-- contents -->"] + items + ["<!-- /contents -->"]
    t = doc.title_line                      # 1-based: lines[t] is the line after the title
    i = t
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and lines[i].strip() == "**Contents**":          # an older hand-made list: take its place
        j = i + 1
        while j < len(lines) and (not lines[j].strip() or lines[j].lstrip().startswith("- [")):
            j += 1
        while j > i + 1 and not lines[j - 1].strip():
            j -= 1
        return "\n".join(lines[:i] + block + lines[j:])
    rest = lines[t:]
    return "\n".join(lines[:t] + [""] + block + ([""] if rest and rest[0].strip() else []) + rest)


def refresh_contents(book):
    """Create or refresh the contents block of every chapter file of a book; returns files changed."""
    changed = 0
    for file in sorted(os.listdir(os.path.join(book, "chapters"))) if os.path.isdir(os.path.join(book, "chapters")) else []:
        if re.match(r"^\d+-.*\.md$", file):
            path = os.path.join(book, "chapters", file)
            text = bf.read_text(path)
            new = with_contents(text)
            if new != text:
                bf.write_text(path, new)
                changed += 1
    return changed


# ---------------------------------------------------------------- one book


class BookIndex:
    """Everything the index needs from one book: plan, chapters, ideas, status."""

    def __init__(self, path, root):
        self.path, self.root = path, root
        self.name = os.path.basename(path.rstrip(os.sep))
        self.plan = bf.load_plan(path)
        self.status = bf.read_status(path)["chapters"]
        self.docs = {}
        for ch in self.plan.chapters:
            file = bf.chapter_path(path, ch.number)
            if file:
                self.docs[ch.number] = (file, bf.parse_chapter(bf.read_text(file)))
        self.taught = {}                 # idea -> (SectionDoc, Teach, doc, file)
        for n in sorted(self.docs):
            file, doc = self.docs[n]
            for s in doc.sections:
                for t in s.teaches:
                    self.taught.setdefault(t.id, (s, t, doc, file))

    def rel(self, file):
        """Path from the book folder."""
        return os.path.relpath(file, self.path).replace(os.sep, "/")

    def term(self, idea):
        """(term, all words, definition) of a written idea."""
        sec, t, doc, _ = self.taught[idea]
        words, _ = bf.idea_words(t, doc.lines)
        term = t.words[0] if t.words else bf.idea_term(t, doc.lines)
        return term, words or [term], bf.definition(t, doc.lines)

    def where(self, idea):
        """Section number where an idea is taught: its marker if written, else the plan."""
        if idea in self.taught:
            return self.taught[idea][0].number
        sec = self.plan.teacher().get(idea)
        return sec.number if sec else None

    def chapter_state(self, ch):
        """planned, writing, written or reviewed."""
        recorded = self.status.get(str(ch.number), {}).get("state", "")
        if ch.number not in self.docs:
            return "planned"
        if recorded in ("written", "reviewed"):
            return recorded
        done = {s.number for s in self.docs[ch.number][1].sections}
        return "written" if {s.number for s in ch.sections} <= done else "writing"

    def section_link(self, number):
        """'chapters/08-x.md#82-...' for a written section, else ''."""
        ch = bf.section_key(number)[0]
        if ch not in self.docs:
            return ""
        file, doc = self.docs[ch]
        sec = doc.section(number)
        return "%s#%s" % (self.rel(file), bf.anchor("%s %s" % (sec.number, sec.title))) if sec else ""

    # ------------------------------------------------------------ manifest and search

    def manifest(self):
        """The book's entry in manifest.json, its edges and its search entries."""
        parts, search = [], []
        for ch in self.plan.chapters:
            if not parts or parts[-1]["title"] != ch.part:
                parts.append({"title": ch.part, "chapters": []})
            parts[-1]["chapters"].append(self.chapter_entry(ch, search))
        edges = []
        for psec in self.plan.sections():
            for idea in psec.needs:
                to = self.where(idea)
                if to and to != psec.number:
                    e = {"from": "%s:%s" % (self.name, psec.number), "to": "%s:%s" % (self.name, to), "idea": idea}
                    if e not in edges:
                        edges.append(e)
        return {"name": self.name, "title": self.plan.title, "for": self.plan.audience, "parts": parts}, edges, search

    def chapter_entry(self, ch, search):
        """One chapter of the manifest; adds its sections to search."""
        file, doc = self.docs.get(ch.number, (None, None))
        sections = []
        numbers = [s.number for s in ch.sections] + [s.number for s in (doc.sections if doc else [])
                                                      if not any(p.number == s.number for p in ch.sections)]
        for number in numbers:
            psec = self.plan.section(number)
            wsec = doc.section(number) if doc else None
            title = wsec.title if wsec else psec.title
            teaches = [t.id for t in wsec.teaches] if wsec else list(psec.teaches)
            entry = {"id": number, "title": title, "kind": psec.kind if psec else "lesson",
                     "level": psec.level if psec else 1, "state": "written" if wsec else "planned",
                     "words": wsec.words if wsec else 0, "teaches": teaches,
                     "anchor": bf.anchor("%s %s" % (number, title))}
            sections.append(entry)
            search.append(self.search_entry(entry, file, doc, wsec))
        out = {"n": ch.number, "title": ch.title, "file": "%s/%s" % (self.name, self.rel(file)) if file else None,
               "state": self.chapter_state(ch), "words": sum(s["words"] for s in sections), "sections": sections}
        unrun = sum("unrun" in c.attrs for s in (doc.sections if doc else []) for c in s.code)
        if unrun:                                    # programs and sessions that could not be run where the book was written
            out["unrun"] = unrun
        return out

    def search_entry(self, entry, file, doc, wsec):
        """One section in search.json: title, terms and the opening words of The idea."""
        terms = []
        for idea in entry["teaches"]:
            terms += self.term(idea)[1] if idea in self.taught else [bf.humanise(idea)]
        out = {"book": self.name, "id": entry["id"], "title": entry["title"], "state": entry["state"],
               "terms": list(dict.fromkeys(terms)), "file": None, "lines": None, "idea": ""}
        if wsec:
            out["file"] = "%s/%s" % (self.name, self.rel(file))
            out["lines"] = [wsec.line, wsec.end]
            out["idea"] = opening_words(doc, wsec, 40)
        return out

    # ------------------------------------------------------------ README, KEYTERMS, INDEX

    def readme(self):
        """README.md: title, audience, parts and chapters with links and state."""
        out = ["# " + self.plan.title, NOTE, ""]
        if self.plan.audience:
            out += ["For " + self.plan.audience.rstrip(".") + ".", ""]
        part = None
        for ch in self.plan.chapters:
            if ch.part != part:
                part = ch.part
                if part:
                    out += ([""] if out[-1] else []) + ["## " + part, ""]
            state = self.chapter_state(ch)
            done = len(self.docs[ch.number][1].sections) if ch.number in self.docs else 0
            name = "%d %s" % (ch.number, ch.title)
            link = "[%s](%s)" % (name, self.rel(self.docs[ch.number][0])) if ch.number in self.docs else name
            out.append("- %s · %s · %d of %d sections" % (link, state, done, len(ch.sections)))
        facts = " · [Checked facts](FACTS.md)" if self.facts_md() else ""
        out += ["", "[Key terms](KEYTERMS.md) · [Index](INDEX.md)" + facts, ""]
        return "\n".join(out)

    def facts_md(self):
        """FACTS.md: per chapter each checked fact, how it was checked; then the blocks shown but not run.
        None when the book has neither."""
        out, unrun = ["# Checked facts: " + self.plan.title, NOTE, "",
                      "What this book states that was checked, and how; and the programs and sessions shown "
                      "but not run where it was written."], []
        for ch in self.plan.chapters:
            if ch.number not in self.docs:
                continue
            doc = self.docs[ch.number][1]
            rows = []
            for n, mark in us_plan.checked_marks(doc.lines):
                sec = bf.section_at(doc, n)
                how = ", ".join(x for x in (mark["how"], mark["ref"], mark["date"]) if x)
                rows.append("- §%s: %s — how it was checked: %s" % (sec.number if sec else ch.number,
                                                                     passage_start(doc.lines, n, 140), how))
            if rows:
                out += ["", "## Chapter %d: %s" % (ch.number, ch.title), ""] + rows
            unrun += ["- §%s `%s`: %s" % (s.number, c.id or "(no id)", c.attrs["unrun"] or "no reason given")
                      for s in doc.sections for c in s.code if "unrun" in c.attrs]
        if len(out) == 4 and not unrun:
            return None
        if unrun:
            out += ["", "Shown but not run on the writer's machine:", ""] + unrun
        return "\n".join(out) + "\n"

    def keyterms(self):
        """KEYTERMS.md: per chapter, each term with the sentence that defines it and its section."""
        out = ["# Key terms: " + self.plan.title, NOTE]
        for ch in self.plan.chapters:
            rows = []
            for psec in ch.sections:
                for idea in psec.teaches:
                    if idea in self.taught:
                        term, _, sentence = self.term(idea)
                        rows.append("- **%s** ([§%s](%s)): %s" % (term, psec.number, self.section_link(psec.number), sentence or "(no definition found)"))
            if rows:
                out += ["", "## Chapter %d: %s" % (ch.number, ch.title), ""] + rows
        return "\n".join(out) + "\n"

    def index_md(self):
        """INDEX.md: every written term A to Z with the section that teaches it."""
        entries = []
        for idea in self.taught:
            term = self.term(idea)[0]
            number = self.where(idea)
            entries.append((term.lower().lstrip("`*&#_-. "), term, number))
        out = ["# Index: " + self.plan.title, NOTE]
        letter = None
        for key, term, number in sorted(entries, key=lambda e: (e[0], bf.section_key(e[2]))):
            first = key[:1].upper() if key[:1].isalpha() else "Symbols"
            if first != letter:
                letter = first
                out += ["", "## " + letter, ""]
            out.append("- %s: [%s](%s)" % (term, number, self.section_link(number)))
        return "\n".join(out) + "\n"


def passage_start(lines, at, n):
    """The first n characters of the passage a mark at line `at` stands for: comments and fence lines out,
    spacing collapsed."""
    kept = [re.sub(r"<!--.*?-->", "", l) for l in bf.passage_above(lines, at, cap=40)]
    text = " ".join(" ".join(l.split()) for l in kept if not re.match(r"^\s*(`{3,}|~{3,})", l))
    return " ".join(text.split())[:n]


def opening_words(doc, sec, n):
    """The first n words of a section's 'The idea' beat (or of its prose), markup stripped."""
    rng = bf.beat_range(doc, sec, "The idea") or (sec.line + 1, sec.end)
    scanned, _ = bf.scan_lines(doc.lines)
    words = []
    for ln, kind, body in scanned[rng[0] - 1:rng[1]]:
        if kind != "prose" or body.lstrip().startswith(("#", "|", "!", "<")):
            continue
        words += re.sub(r"[*`_]|\]\([^)]*\)|[\[\]]", "", body).split()
        if len(words) >= n:
            break
    return " ".join(words[:n])

# ---------------------------------------------------------------- main


def inside(path, folder):
    """True if path is folder or under it."""
    path, folder = os.path.realpath(path), os.path.realpath(folder)
    return path == folder or path.startswith(folder + os.sep)


def main(argv):
    if "--help" in argv or "-h" in argv:
        print(__doc__.strip())
        return 0
    args = [a for a in argv if not a.startswith("--")]
    if args:
        named = [bf.resolve_book(args[0])]
        root = os.path.dirname(named[0].rstrip(os.sep))
        if not os.path.exists(os.path.join(named[0], "PLAN.md")):
            print("no PLAN.md in %s; write one, or run us_plan.py from-chapters" % named[0])
            return 1
    else:
        root = bf.book_root()
        named = bf.list_books(root)
    private = bf.private_dir()
    if inside(root, private) or inside(private, root):
        print("the book root and the private folder overlap; keep them apart (understudy.yaml book: and private:)")
        return 1
    books, stats = [], [0, 0, 0, 0]
    for path in bf.list_books(root):
        if not os.path.exists(os.path.join(path, "PLAN.md")):
            continue
        if path in named:
            refresh_contents(path)
        bk = BookIndex(path, root)
        if path in named and us_plan.check_plan(bk.plan)[0]:
            print("note: %s/PLAN.md has problems; run us_plan.py check %s" % (bk.name, bk.name))
        if path in named:
            write_if_changed(os.path.join(path, "README.md"), bk.readme())
            write_if_changed(os.path.join(path, "KEYTERMS.md"), bk.keyterms())
            write_if_changed(os.path.join(path, "INDEX.md"), bk.index_md())
            facts, facts_path = bk.facts_md(), os.path.join(path, "FACTS.md")
            if facts:
                write_if_changed(facts_path, facts)
            elif os.path.exists(facts_path) and NOTE in bf.read_text(facts_path):
                os.remove(facts_path)                # the last mark went: a generated FACTS.md goes too
        books.append((bk, path in named))
    manifest = {"schema": SCHEMA, "books": [], "edges": [], "chapter_edges": []}
    search = {"schema": SCHEMA, "sections": []}
    for bk, mine in books:
        entry, edges, found = bk.manifest()
        manifest["books"].append(entry)
        manifest["edges"] += edges
        search["sections"] += found
        if mine:
            stats[0] += len(bk.plan.chapters)
            stats[1] += len(found)
            stats[2] += len(set(bk.plan.teacher()) | set(bk.taught))
            stats[3] += len(edges)
    agg = {}
    for e in manifest["edges"]:
        key = (e["from"].split(".")[0], e["to"].split(".")[0])
        if key[0] != key[1]:
            agg[key] = agg.get(key, 0) + 1
    manifest["chapter_edges"] = [{"from": a, "to": b, "ideas": n} for (a, b), n in sorted(agg.items())]
    if books:
        write_if_changed(os.path.join(root, "manifest.json"), json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
        write_if_changed(os.path.join(root, "search.json"), json.dumps(search, separators=(",", ":"), ensure_ascii=False) + "\n")
    n = sum(1 for _, mine in books if mine)
    print("indexed %d book%s: %d chapters, %d sections, %d terms, %d edges" % (n, "" if n == 1 else "s", *stats))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
